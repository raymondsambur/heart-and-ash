export type IconName = keyof typeof ART;
export const ICON_NAMES = Object.keys(ART) as IconName[];

export function hasIcon(name: string): name is IconName {
  return Object.prototype.hasOwnProperty.call(ART, name);
}

export interface IconOpts {
  /** Edge length: a number is px, a string is any CSS length. Default: 1em (inherits the font size). */
  size?: number | string;
  /** Extra class names for the wrapping span. */
  cls?: string;
  /** CSS colour (default currentColor). */
  color?: string;
  /** Accessible name. Omit for decorative icons (aria-hidden). */
  title?: string;
  /** Stroke width on the 24 grid (default 1.7). */
  stroke?: number;
}

function shapeSvg(spec: string): string {
  const c = spec[0];
  if (c === '*') return `<path d="${spec.slice(1)}" fill="currentColor" stroke="currentColor" stroke-width="0.8"/>`;
  if (c === '~') return `<path d="${spec.slice(1)}" fill="currentColor" fill-opacity="0.2"/>`;
  return `<path d="${spec}"/>`;
}

/** Inner markup (no wrapper) for an icon; unknown names fall back to the generic `unknown` icon. */
export function iconBody(name: string): string {
  const art: readonly string[] = hasIcon(name) ? ART[name] : ART.unknown;
  return art.map(shapeSvg).join('');
}

/** A standalone `<svg>` string, safe to inline or to embed in a data URI. */
export function iconSvg(name: string, opts: IconOpts = {}): string {
  const size = opts.size === undefined ? '1em' : typeof opts.size === 'number' ? `${opts.size}px` : opts.size;
  const label = opts.title ? ` role="img" aria-label="${opts.title.replace(/"/g, '&quot;')}"` : ' aria-hidden="true" focusable="false"';
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="${size}" height="${size}" fill="none" stroke="currentColor" stroke-width="${opts.stroke ?? 1.7}" stroke-linecap="round" stroke-linejoin="round"${label}>${iconBody(name)}</svg>`;
}

/** DOM icon: `<span class="ico ico-NAME">` wrapping the SVG. Sizes with the surrounding font unless `size` is given. */
export function icon(name: string, opts: IconOpts = {}): HTMLSpanElement {
  const el = document.createElement('span');
  el.className = ['ico', `ico-${hasIcon(name) ? name : 'unknown'}`, opts.cls].filter(Boolean).join(' ');
  if (opts.color) el.style.color = opts.color;
  el.innerHTML = iconSvg(name, { ...opts, size: '100%' });
  if (opts.size !== undefined) {
    const px = typeof opts.size === 'number' ? `${opts.size}px` : opts.size;
    el.style.width = px;
    el.style.height = px;
  }
  return el;
}

/** Faction id -> emblem icon (falls back to a plain flag). */
export function factionIconName(id: string): IconName {
  const name = `faction${id.charAt(0).toUpperCase()}${id.slice(1)}`;
  return hasIcon(name) ? name : 'flag';
}

/** Rank id (1-8) -> medal icon. */
export function rankIconName(rank: number): IconName {
  return `rank${Math.max(1, Math.min(8, Math.round(rank)))}` as IconName;
}

