  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" width="${size}" height="${size}"><rect width="64" height="64" rx="11" fill="#c8452d"/><rect x="2.500" y="2.500" width="59" height="59" rx="9" fill="none" stroke="#f7e6c8" stroke-opacity="0.35"/><g transform="translate(8 8) scale(2)" fill="none" stroke="#f7e6c8" stroke-width="1.500" stroke-linecap="round" stroke-linejoin="round">${iconBody('logo')}</g></svg>`;
