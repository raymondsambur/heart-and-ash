const o = (cx: number, cy: number, r: number): string => `M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0z`;
const dot = (x: number, y: number, r = 1.05): string => `*${o(x, y, r)}`;
const tint = (d: string): string => `~${d}`;

/** Medal rank badge: a disc with `n` pips and two ribbon tails. */
function rankArt(n: number): string[] {
  const pips: string[] = [];
  const rows = n <= 4 ? [n] : [Math.ceil(n / 2), Math.floor(n / 2)];
  rows.forEach((count, ri) => {
    const y = rows.length === 1 ? 10 : 8.4 + ri * 3.2;
    for (let i = 0; i < count; i++) pips.push(dot(12 + (i - (count - 1) / 2) * 2.7, y, 0.95));
  });
  return [tint(o(12, 10, 6.8)), 'M8.4 15.6 7 21l5-2.2L17 21l-1.4-5.4', ...pips];
}

/** Tier marker: `n` small diamonds in a row. */
function tierArt(n: number): string[] {
  const out: string[] = [];
  for (let i = 0; i < n; i++) {
    const x = 12 + (i - (n - 1) / 2) * 5;
    out.push(`*M${x} 8.5l2.2 3.5-2.2 3.5-2.2-3.5z`);
  }
  return out;
}

